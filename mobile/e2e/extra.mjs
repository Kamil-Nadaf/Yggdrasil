import puppeteer from 'puppeteer-core';
const B = process.env.BASE; const MOCK = process.env.MOCK || 'http://localhost:18000';
const res = []; const check = (n, ok, x = '') => { res.push(ok); console.log(`${ok ? 'PASS' : 'FAIL'}  ${n}${x ? ' — ' + x : ''}`); };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const br = await puppeteer.launch({ executablePath: process.env.CHROME, headless: true, args: ['--no-sandbox'] });
const p = await br.newPage(); await p.setViewport({ width: 390, height: 844, isMobile: true });
const errs = []; p.on('pageerror', (e) => errs.push(String(e)));
let hits = 0; p.on('request', (r) => { if (r.url().includes('/ygg/api/tasks')) hits++; });
await p.goto(`${B}/#/today`);
await p.evaluate((t) => localStorage.setItem('ygg.v1', JSON.stringify({ settings: { token: t } })), process.env.SYNC_TOKEN);
await p.reload(); await sleep(1200);
const before = hits;
check('Sync button next to gear', !!(await p.$('button[aria-label="Sync now"]')));
await p.click('button[aria-label="Sync now"]'); await sleep(900);
check('Sync button refetches data', hits > before, `${before}->${hits}`);
await p.evaluate(() => { location.hash = '#/settings'; }); await sleep(500);
await p.evaluate(() => [...document.querySelectorAll('button')].find((b) => b.textContent.includes('Check for updates')).click()); await sleep(900);
check('Check for updates says latest', (await p.evaluate(() => document.body.innerText)).includes('latest version'));
await p.evaluate(() => { location.hash = '#/sync'; }); await sleep(700);
await p.type('#zuid', '12345'); await p.type('#zkey', 'abcSECRET');
await p.evaluate(() => [...document.querySelectorAll('button')].find((b) => b.textContent.includes('Save Zotero')).click()); await sleep(800);
check('Zotero save confirmed', (await p.evaluate(() => document.body.innerText)).includes('Saved to your Yggdrasil backend'));
const body = await p.evaluate(() => document.body.innerText);
check('Zotero key not shown back', !body.includes('abcSECRET') && body.includes('A key is saved'));
check('No page errors', errs.length === 0, errs.join('|'));
await br.close(); const f = res.filter((x) => !x).length; console.log(`${res.length - f}/${res.length}`); process.exit(f ? 1 : 0);
