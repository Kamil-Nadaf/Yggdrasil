import puppeteer from 'puppeteer-core';
import { writeFileSync } from 'node:fs';
const B = process.env.BASE;
const res = []; const check = (n, ok, x = '') => { res.push(ok); console.log(`${ok ? 'PASS' : 'FAIL'}  ${n}${x ? ' — ' + x : ''}`); };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const br = await puppeteer.launch({ executablePath: process.env.CHROME, headless: true, args: ['--no-sandbox'] });
const p = await br.newPage(); await p.setViewport({ width: 390, height: 844, isMobile: true });
const errs = []; p.on('pageerror', (e) => errs.push(String(e)));
const yggCalls = []; p.on('request', (r) => { if (r.url().includes('/ygg/')) yggCalls.push(r.url()); });
const answers = []; p.on('dialog', async (d) => { await d.accept(answers.shift() ?? ''); });
const go = async (h) => { await p.evaluate((h) => { location.hash = h; }, h); await sleep(600); };
const text = () => p.evaluate(() => document.body.innerText);
await p.goto(`${B}/#/today`);
await p.evaluate(() => localStorage.setItem('ygg.v1', JSON.stringify({ settings: { mode: 'local' } })));
await p.reload(); await sleep(1500); yggCalls.length = 0;
await go('#/tasks');
answers.push('Thesis'); await p.click('button[aria-label="New project"]'); await sleep(600);
check('Local: project created', (await text()).includes('Thesis'));
await p.evaluate(() => [...document.querySelectorAll('a.card')].find((a) => a.textContent.includes('Thesis')).click()); await sleep(600);
answers.push('Write intro'); await p.click('button[aria-label="New main task"]'); await sleep(600);
await p.evaluate(() => [...document.querySelectorAll('button.plainbtn')].find((b) => b.textContent.includes('Write intro')).click()); await sleep(500);
answers.push('Draft section 1'); await p.evaluate(() => [...document.querySelectorAll('button')].find((b) => /add subtask|new subtask|\+/i.test(b.textContent) || b.getAttribute('aria-label')?.match(/subtask/i)).click()); await sleep(600);
check('Local: subtask created', (await text()).includes('Draft section 1'));
await go('#/today');
check('Local: Active tasks card shows the task', (await text()).includes('Write intro'));
await go('#/notes');
answers.push('Ideas/Pulse'); await p.click('.fab'); await sleep(900);
check('Local: note created and opened', (await p.evaluate(() => location.hash)).includes('Ideas'));
await p.type('textarea', 'hello phone'); await sleep(2500);
await go('#/notes');
check('Local: note listed', (await text()).includes('Pulse'));
await go('#/arxiv'); await sleep(1500);
check('Local: arXiv offline gives readable error', /arXiv|Cannot reach/i.test(await text()));
await go('#/write');
check('Local: Write screen loads', (await text()).includes('Write'));
await go('#/sync');
check('Local: Phone only page', (await text()).includes('Everything is stored on this phone'));
const bk = { format: 'yggdrasil-phone-backup', version: 1, db: { notes: { 'Other.md': { source: 'from mac', modified: '2030-01-01T00:00:00Z' } }, tex: {}, cols: [], items: {}, habits: {}, goals: [], projects: [], log: {} } };
writeFileSync('/tmp/bk.json', JSON.stringify(bk));
await (await p.$('input[type=file]')).uploadFile('/tmp/bk.json'); await sleep(700);
check('Backup import merges', (await text()).includes('Merged 1 change'));
await go('#/notes');
check('Imported note appears', (await text()).includes('Other'));
check('No requests to /ygg in phone-only mode', yggCalls.length === 0, yggCalls.join(','));
check('No page errors', errs.length === 0, errs.join('|'));
await br.close(); const f = res.filter((x) => !x).length; console.log(`${res.length - f}/${res.length}`); process.exit(f ? 1 : 0);
